const LanguageContext = createContext(null);

export const LanguageProvider = ({ children }) => {
    // Get initial language from localStorage or default to Portuguese
    const [language, setLanguage] = useState(() => {
        if (typeof window !== 'undefined') {
            return localStorage.getItem('elis-language') || 'pt';
        }
        return 'pt';
    });

    // Toggle between English and Portuguese
    const toggleLanguage = useCallback(() => {
        setLanguage(prev => {
            const newLang = prev === 'pt' ? 'en' : 'pt';
            localStorage.setItem('elis-language', newLang);
            return newLang;
        });
    }, []);

    // Set specific language
    const setLang = useCallback((lang) => {
        if (lang === 'pt' || lang === 'en') {
            setLanguage(lang);
            localStorage.setItem('elis-language', lang);
        }
    }, []);

    // Translation function
    const t = useCallback((key, params = {}) => {
        let text = translations[language]?.[key] || translations['pt']?.[key] || key;

        // Simple interpolation
        if (params && typeof params === 'object') {
            Object.keys(params).forEach(param => {
                text = text.replace(new RegExp(`\\{${param}\\}`, 'g'), params[param]);
            });
        }

        return text;
    }, [language]);

    // Get locale for date formatting
    const locale = language === 'pt' ? 'pt-BR' : 'en-US';

    const value = {
        language,
        toggleLanguage,
        setLanguage: setLang,
        t,
        locale,
        isPortuguese: language === 'pt',
        isEnglish: language === 'en',
    };

    return (
        <LanguageContext.Provider value={value}>
            {children}
        </LanguageContext.Provider>
    );
};

export const useLanguage = () => {
    const context = useContext(LanguageContext);
    if (!context) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
};

/**
 * Standalone translation function for use outside of React components
 * (e.g., in api.js or other service files)
 * Reads the language from localStorage and returns the translated string
 * @param {string} key - The translation key
 * @returns {string} The translated string or the key if not found
 */
export const translate = (key, params = {}) => {
    const language = (typeof window !== 'undefined' && localStorage.getItem('elis-language')) || 'pt';
    let text = translations[language]?.[key] || translations['pt']?.[key] || key;

    // Simple interpolation
    if (params && typeof params === 'object') {
        Object.keys(params).forEach(param => {
            text = text.replace(new RegExp(`\\{${param}\\}`, 'g'), params[param]);
        });
    }

    return text;
};

export default LanguageContext;
